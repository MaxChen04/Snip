// The cloud runbooks, verbatim. One module because two surfaces must say the same thing:
// the MCP `setup_cloud` / `pull_cloud` prompts (web/worker/mcp.ts) and the Copy-prompt button in
// Settings. Contracts §6 requires them to be the same text, so neither may hold its own copy.
//
// Both are instructions to an agent, not to a person: they sequence the CLI, pause where a human
// is needed, and forbid improvising. The engine does the work.

const lines = (...rows: string[]) => rows.join("\n")

export const SETUP_CLOUD_PROMPT = lines(
  "Set up Snip cloud for this library. Snip runs locally today. Enabling cloud copies this library into the user's own Cloudflare account, then points the app at that copy; the local library stays behind as a snapshot.",
  "",
  "1. Check before changing anything: run `npm run setup:cloudflare -- setup --check --json` from the repository root. If the status shows mode \"enabling\" or \"cloud\", or a cloud copy already exists, stop and tell the user what exists. Never start a second setup.",
  "2. Show the plan and wait for approval. In a few sentences: the library is copied to their Cloudflare account; the local copy stays as a snapshot; Cloudflare asks them to sign in and Allow once; R2 may ask for a card the first time; at the end the app asks for Touch ID or the owner link.",
  "3. Run `npm run setup:cloudflare -- setup --yes --json` and read the NDJSON events as they arrive.",
  "   - When an event has type \"human\" (actions enable_r2 or open_url), pause and tell the user exactly what to do in the browser, then continue.",
  "   - If it exits 2 with event \"needs_input\", ask only for those values and rerun with the matching flags.",
  "   - Never ask for a secret in chat. SESSION_SECRET, CAPTURE_TOKEN and OWNER_LINK_SECRET are generated by the engine, and Cloudflare credentials come from `wrangler login`.",
  "4. On success, report the URL from the result event and confirm the app now points at the cloud library.",
  "5. On failure, run `npm run doctor` and report its output together with the failed step id. Do not retry blindly.",
)

export const PULL_CLOUD_PROMPT = lines(
  "Bring this Mac's cloud Snip library back to a local copy. The cloud copy stays live and reachable after the pull; nothing is deleted.",
  "",
  "1. Run `npm run setup:cloudflare -- status --json` and confirm mode is \"cloud\". If it is not, stop and say so.",
  "2. Show the plan and wait for approval: the cloud library is copied into a new local state directory, verified against the cloud, and the app switches back to local. The cloud copy keeps working, including for other devices and agents.",
  "3. Run `npm run setup:cloudflare -- pull --json` and read the NDJSON events. Pause at any \"human\" event and tell the user what to do.",
  "4. Never ask for a secret in chat; the engine mints and deletes TRANSFER_TOKEN itself.",
  "5. On failure, run `npm run doctor` and report its output together with the failed step id.",
)
