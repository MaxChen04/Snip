#!/usr/bin/env node
// Deploys your own Snip to Cloudflare's free plan.
//
//   npm run setup:cloudflare     first deploy, or repair one: creates D1, KV and R2 if missing,
//                                writes web/wrangler.deploy.jsonc, sets secrets, migrates, deploys
//   npm run deploy               rebuild and deploy with web/wrangler.deploy.jsonc
//   npm run db:migrate:remote    apply pending migrations to the deployed D1 database
//
// web/wrangler.deploy.jsonc holds your install's ids, URL and login. It is gitignored, so
// `npm run update` and git pulls never conflict with it. The tracked web/wrangler.jsonc keeps
// placeholders and is what local development uses.

import { spawnSync } from "node:child_process"
import crypto from "node:crypto"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import readline from "node:readline/promises"
import { fileURLToPath, pathToFileURL } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const WEB = path.join(ROOT, "web")
export const TRACKED_CONFIG = path.join(WEB, "wrangler.jsonc")
export const DEPLOY_CONFIG = path.join(WEB, "wrangler.deploy.jsonc")

/** Preserve local storage identities before the tracked config can be reset. Never overwrite a library's saved config. */
export function preserveLocalConfig(root = ROOT) {
  const web = path.join(root, "web")
  const local = path.join(web, "wrangler.local.jsonc")
  try {
    fs.copyFileSync(path.join(web, "wrangler.jsonc"), local, fs.constants.COPYFILE_EXCL)
  } catch (error) {
    if (error.code !== "EEXIST") throw error
  }
  return local
}


export const PLACEHOLDERS = {
  d1: "REPLACE_WITH_D1_DATABASE_ID",
  kv: "REPLACE_WITH_KV_NAMESPACE_ID",
  login: "your-github-login",
  url: "https://snip.YOUR-SUBDOMAIN.workers.dev",
}

// ---------- Config text (pure, tested) ----------

const field = (text, key) => text.match(new RegExp(`"${key}"\\s*:\\s*"([^"]*)"`))?.[1] ?? null

/** Values in a wrangler.jsonc, or null where it still has a placeholder. */
export function readValues(text) {
  const value = (key, placeholder) => {
    const v = field(text, key)
    return v && v !== placeholder && !/YOUR-SUBDOMAIN|REPLACE_WITH/.test(v) ? v : null
  }
  return {
    d1: value("database_id", PLACEHOLDERS.d1),
    kv: value("id", PLACEHOLDERS.kv),
    login: value("ALLOWED_GITHUB_LOGINS", PLACEHOLDERS.login),
    url: value("PUBLIC_URL", PLACEHOLDERS.url),
  }
}

/** The tracked config with this install's values filled in. Comments and layout are kept. */
export function renderDeployConfig(template, { d1, kv, login, url }) {
  const set = (text, key, value) => {
    const re = new RegExp(`("${key}"\\s*:\\s*)"[^"]*"`)
    if (!re.test(text)) throw new Error(`web/wrangler.jsonc has no "${key}" to fill in`)
    return text.replace(re, (_, head) => `${head}${JSON.stringify(value)}`)
  }
  let out = template
  out = set(out, "database_id", d1)
  out = set(out, "id", kv)
  out = set(out, "ALLOWED_GITHUB_LOGINS", login)
  out = set(out, "PUBLIC_URL", url.replace(/\/$/, ""))
  return `// Generated by \`npm run setup:cloudflare\` for this install. Gitignored: keep it out of commits.\n// Re-run setup after web/wrangler.jsonc changes upstream; it keeps the values below.\n${out}`
}

/** A workers.dev subdomain, a bare host or a URL, as the Worker's public origin. */
export function publicUrlFrom(input, worker = "snip") {
  const raw = String(input ?? "").trim().replace(/\/+$/, "")
  if (!raw) return null
  if (/^https?:\/\//i.test(raw)) return new URL(raw).origin
  if (raw.includes(".")) return `https://${raw}`
  return `https://${worker}.${raw}.workers.dev`
}

/** The id printed by `wrangler d1 create` or `wrangler kv namespace create`. */
export function parseCreatedId(output, key) {
  return output.match(new RegExp(`"?${key}"?\\s*[:=]\\s*"([0-9a-f-]{20,})"`))?.[1] ?? null
}

// ---------- Commands ----------

const log = (message) => console.log(`\x1b[1m›\x1b[0m ${message}`)
const fail = (message) => {
  console.error(`\n\x1b[31m✗\x1b[0m ${message}`)
  process.exit(1)
}

function wrangler(args, { capture = false, input } = {}) {
  const result = spawnSync("npx", ["--no-install", "wrangler", ...args], {
    cwd: WEB,
    encoding: "utf8",
    input,
    stdio: capture || input !== undefined ? ["pipe", "pipe", "inherit"] : "inherit",
    env: { ...process.env, WRANGLER_SEND_METRICS: "false" },
  })
  if (result.error) fail(`Couldn't run wrangler: ${result.error.message}. Run \`npm install\` first.`)
  return { ok: result.status === 0, out: result.stdout ?? "" }
}

function configPath() {
  if (fs.existsSync(DEPLOY_CONFIG)) return DEPLOY_CONFIG
  const values = readValues(fs.readFileSync(TRACKED_CONFIG, "utf8"))
  if (values.d1 && values.kv && values.login && values.url) return TRACKED_CONFIG // An older install that edited the tracked file.
  fail("No deploy config yet. Run `npm run setup:cloudflare` first; it creates web/wrangler.deploy.jsonc.")
}

export const DEPLOY_OUT_DIR = "dist-deploy"

function deploy(config) {
  log("Building the web app")
  // The Cloudflare Vite plugin points web/.wrangler/deploy/config.json at its latest build.
  // Put it back afterwards so local commands keep using the local config and library.
  const redirect = path.join(WEB, ".wrangler/deploy/config.json")
  const before = fs.existsSync(redirect) ? fs.readFileSync(redirect) : null
  const build = spawnSync("npx", ["--no-install", "vite", "build"], {
    cwd: WEB,
    stdio: "inherit",
    env: { ...process.env, SNIP_WRANGLER_CONFIG: config, SNIP_OUT_DIR: DEPLOY_OUT_DIR },
  })
  if (before) fs.writeFileSync(redirect, before)
  else fs.rmSync(redirect, { force: true })
  if (build.status !== 0) fail("The build failed. Fix the error above and run it again.")
  log("Deploying the Worker")
  if (!wrangler(["deploy", "--config", path.join(DEPLOY_OUT_DIR, "snip/wrangler.json")]).ok) fail("Deploy failed. Fix the error above and run it again.")
}

function migrate(config) {
  log("Applying database migrations")
  if (!wrangler(["d1", "migrations", "apply", "snip", "--remote", "--config", config]).ok) fail("Migrations failed. Fix the error above and run it again.")
}

async function ask(rl, question, fallback) {
  const answer = (await rl.question(`${question}${fallback ? ` [${fallback}]` : ""}: `)).trim()
  return answer || fallback || ""
}

function askHidden(question) {
  return new Promise((resolve) => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true })
    const write = rl._writeToOutput?.bind(rl)
    rl._writeToOutput = (s) => (s.includes(question) ? write?.(s) : write?.("*"))
    rl.question(question).then((answer) => {
      rl.close()
      process.stdout.write("\n")
      resolve(answer.trim())
    })
  })
}

const randomSecret = () => crypto.randomBytes(32).toString("hex")

function guessLogin() {
  const r = spawnSync("git", ["config", "github.user"], { encoding: "utf8" })
  return r.status === 0 ? r.stdout.trim() : ""
}

function findOrCreateD1() {
  const list = wrangler(["d1", "list", "--json"], { capture: true })
  try {
    const found = JSON.parse(list.out).find((db) => db.name === "snip")
    if (found?.uuid) return found.uuid
  } catch { /* not JSON: fall through to create */ }
  log("Creating the D1 database `snip`")
  const created = wrangler(["d1", "create", "snip"], { capture: true })
  const id = parseCreatedId(created.out, "database_id")
  if (!created.ok || !id) fail(`Couldn't create the D1 database.\n${created.out}`)
  return id
}

function findOrCreateKv() {
  const list = wrangler(["kv", "namespace", "list"], { capture: true })
  try {
    const found = JSON.parse(list.out).find((ns) => ns.title === "OAUTH_KV" || ns.title === "snip-OAUTH_KV")
    if (found?.id) return found.id
  } catch { /* fall through */ }
  log("Creating the KV namespace `OAUTH_KV`")
  const created = wrangler(["kv", "namespace", "create", "OAUTH_KV"], { capture: true })
  const id = parseCreatedId(created.out, "id")
  if (!created.ok || !id) fail(`Couldn't create the KV namespace.\n${created.out}`)
  return id
}

function ensureR2() {
  const list = wrangler(["r2", "bucket", "list"], { capture: true })
  if (/\bsnip-files\b/.test(list.out)) return
  log("Creating the R2 bucket `snip-files`")
  const created = wrangler(["r2", "bucket", "create", "snip-files"], { capture: true })
  if (!created.ok && !/already exists/i.test(created.out)) fail(`Couldn't create the R2 bucket. R2 must be enabled once in the Cloudflare dashboard (R2 → Get started).\n${created.out}`)
}

function existingSecrets(config) {
  const r = wrangler(["secret", "list", "--config", config, "--format", "json"], { capture: true })
  try {
    return new Set(JSON.parse(r.out).map((s) => s.name))
  } catch {
    return new Set()
  }
}

function putSecrets(config, secrets) {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "snip-secrets-")), "secrets.json")
  try {
    fs.writeFileSync(file, JSON.stringify(secrets), { mode: 0o600 })
    if (!wrangler(["secret", "bulk", file, "--config", config]).ok) fail("Couldn't set the Worker secrets.")
  } finally {
    fs.rmSync(path.dirname(file), { recursive: true, force: true })
  }
}

function writeCaptureEnv(url, token) {
  const file = path.join(ROOT, "capture/.env")
  const example = fs.readFileSync(path.join(ROOT, "capture/.env.example"), "utf8")
  const base = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : example
  const set = (text, key, value) => (new RegExp(`^${key}=.*$`, "m").test(text) ? text.replace(new RegExp(`^${key}=.*$`, "m"), `${key}=${value}`) : `${text.trimEnd()}\n${key}=${value}\n`)
  fs.writeFileSync(file, set(set(base, "SNIP_URL", url), "CAPTURE_TOKEN", token), { mode: 0o600 })
}

async function setup() {
  console.log("\nSnip on Cloudflare\n")
  preserveLocalConfig()
  log("Preserved local library config in web/wrangler.local.jsonc (gitignored)")
  if (!wrangler(["whoami"], { capture: true }).out.match(/associated with the email|You are logged in/i)) {
    log("Signing in to Cloudflare")
    if (!wrangler(["login"]).ok) fail("Cloudflare sign-in didn't finish.")
  }

  // Keep what an earlier setup (or an older, hand-edited tracked config) already chose.
  const previous = fs.existsSync(DEPLOY_CONFIG) ? readValues(fs.readFileSync(DEPLOY_CONFIG, "utf8")) : readValues(fs.readFileSync(TRACKED_CONFIG, "utf8"))
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout })
  const login = previous.login ?? (await ask(rl, "Your GitHub login (the only account allowed to sign in)", guessLogin()))
  if (!login) fail("A GitHub login is required.")
  const url =
    previous.url ??
    publicUrlFrom(await ask(rl, "Your workers.dev subdomain, shown in the Cloudflare dashboard under Workers & Pages (e.g. max-chen), or a custom domain"))
  if (!url) fail("A subdomain or URL is required.")
  rl.close()

  const d1 = previous.d1 ?? findOrCreateD1()
  const kv = previous.kv ?? findOrCreateKv()
  ensureR2()
  fs.writeFileSync(DEPLOY_CONFIG, renderDeployConfig(fs.readFileSync(TRACKED_CONFIG, "utf8"), { d1, kv, login, url }))
  log(`Wrote ${path.relative(ROOT, DEPLOY_CONFIG)} (gitignored)`)

  migrate(DEPLOY_CONFIG)
  deploy(DEPLOY_CONFIG)

  const have = existingSecrets(DEPLOY_CONFIG)
  const secrets = {}
  if (!have.has("GITHUB_CLIENT_ID") || !have.has("GITHUB_CLIENT_SECRET")) {
    console.log(`\nCreate a GitHub OAuth app at https://github.com/settings/applications/new with:
  Homepage URL:  ${url}
  Callback URL:  ${url}/auth/callback\n`)
    const rl2 = readline.createInterface({ input: process.stdin, output: process.stdout })
    secrets.GITHUB_CLIENT_ID = await ask(rl2, "OAuth app Client ID")
    rl2.close()
    secrets.GITHUB_CLIENT_SECRET = await askHidden("OAuth app Client secret (hidden): ")
    if (!secrets.GITHUB_CLIENT_ID || !secrets.GITHUB_CLIENT_SECRET) fail("Both the Client ID and a Client secret are required.")
  }
  if (!have.has("SESSION_SECRET")) secrets.SESSION_SECRET = randomSecret()
  let captureToken = null
  if (!have.has("CAPTURE_TOKEN")) captureToken = secrets.CAPTURE_TOKEN = randomSecret()
  if (Object.keys(secrets).length) {
    log(`Setting secrets: ${Object.keys(secrets).join(", ")}`)
    putSecrets(DEPLOY_CONFIG, secrets)
  }

  if (captureToken) {
    const envFile = path.join(ROOT, "capture/.env")
    const current = fs.existsSync(envFile) ? fs.readFileSync(envFile, "utf8").match(/^SNIP_URL=(.*)$/m)?.[1] : null
    let point = !current || current.includes("YOUR-SUBDOMAIN")
    if (!point) {
      const rl3 = readline.createInterface({ input: process.stdin, output: process.stdout })
      point = /^y/i.test(await ask(rl3, `capture/.env points at ${current}. Point it at ${url} instead? (y/N)`, "N"))
      rl3.close()
    }
    if (point) {
      writeCaptureEnv(url, captureToken)
      log("Pointed capture/.env at your Worker")
    } else {
      const file = path.join(ROOT, "capture/.env.cloudflare")
      fs.writeFileSync(file, `SNIP_URL=${url}\nCAPTURE_TOKEN=${captureToken}\n`, { mode: 0o600 })
      log(`Saved the deployed Worker's capture settings to capture/.env.cloudflare. Capture for it with:\n  SNIP_CAPTURE_ENV_FILE="${file}" npm run capture`)
    }
  }

  console.log(`\n\x1b[32m✓\x1b[0m Snip is live at ${url}
  Sign in:      ${url}  (as ${login})
  Capture:      npm run capture   (keep it running to process captures)
  MCP:          ${url}/mcp
  Check setup:  npm run doctor\n`)
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  const command = process.argv[2]
  if (command === "setup") await setup()
  else if (command === "deploy") deploy(configPath())
  else if (command === "migrate") migrate(configPath())
  else fail("Usage: node scripts/cloudflare.mjs setup | deploy | migrate")
}
